"""第三关：由代码选择讲解策略，不让模型自行判断用户水平。"""

ACCURACY_RULES = (
    "两种水平都必须保持专业含义准确：简化语言不能把近似关系写成严格等同。"
    "区分定义、工程近似、假设示例和实际识别能力，术语有多种含义时注明当前语境。"
    "未提供专业资料时，不给出某类任务必须使用某个数值范围的断言；"
    "可以用明确标注为假设的数字帮助理解，不编造标准或来源。"
    "讨论性能权衡时说明相关条件，不把某些系统的特点说成所有系统的必然规律。"
    "生活类比只辅助理解，不能替代定义；只选必要概念，避免内部矛盾。"
)

LEVEL_POLICIES = {
    "beginner": (
        "用户水平：入门。约150至250字。先点明当前知识点，"
        "用直白语言解释含义，给一个明确标注为类比的生活例子，再说明用途。"
        "尽量少用术语，必须用的术语要解释，不堆砌公式。"
    ),
    "advanced": (
        "用户水平：进阶。约200至350字。先点明当前知识点，"
        "给出较严谨的定义，解释相关概念的区别，再说明适用条件和局限。"
        "可以使用专业术语，但要解释关键含义；必要时才给公式，不为显得专业而堆砌术语。"
    ),
}


def explanation_policy(learner_level):
    if learner_level not in LEVEL_POLICIES:
        raise ValueError("用户水平只能是 beginner 或 advanced")
    return LEVEL_POLICIES[learner_level] + ACCURACY_RULES
